"""Write the self-contained Overleaf project of the article: ../methodsx_overleaf/ and its zip.

    sh build.sh && python make_overleaf.py

main.tex and supplement.tex are flattened: every number macro is replaced by its value,
cross-references between the two documents by their printed numbers (read from build/*.aux),
and figure paths point to figures/. Each file then compiles on its own (pdflatex + bibtex),
with references.bib and the figures folder beside it. Never edit the output by hand.
"""
from __future__ import annotations

import re
import shutil
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "methodsx_overleaf"
FIG = HERE.parent / "methodsx_figures" / "out"
FIGS = ["fig_validation.pdf", "fig_sites_map.pdf"]


def macros() -> dict[str, str]:
    v = {}
    for f in ("numbers.tex", "val_numbers.tex"):
        v.update(re.findall(r"^\\newcommand\{\\(v\w+|fit\w+)\}\{(.*)\}[ \t]*(?:%.*)?$", (HERE / f).read_text(), re.M))
    return v


def labels(aux: Path) -> dict[str, str]:
    """Label -> printed number, from a LaTeX .aux file."""
    return dict(re.findall(r"\\newlabel\{([^}]+)\}\{\{([^}]*)\}", aux.read_text()))


PREAMBLE_MACROS = r"""\newcommand{\todo}[1]{\textcolor{red}{[TODO: #1]}}
\newcommand{\RePV}{RePV}
\DeclareRobustCommand{\cF}{\tikz[baseline=-0.6ex]\fill (0,0) circle (0.55ex);}
\DeclareRobustCommand{\cN}{\tikz[baseline=-0.6ex]\draw[line width=0.4pt] (0,0) circle (0.55ex);}
"""


def flatten(src: str, values: dict[str, str], external: dict[str, str]) -> str:
    out = []
    for line in src.splitlines(keepends=True):
        if line.lstrip().startswith(r"\externaldocument") or line.strip() == r"\usepackage{xr-hyper}":
            continue
        out.append(line)
    t = "".join(out)
    t = t.replace(r"\input{macros}", PREAMBLE_MACROS.strip())
    # inline \input of generated tables
    t = re.sub(r"\\IfFileExists\{worked_example\.tex\}\{\\input\{worked_example\}\}\{[^\n]*\}",
               lambda m: (HERE / "worked_example.tex").read_text(), t)
    t = re.sub(r"\\input\{(val_\w+|worked_example)\}", lambda m: (HERE / f"{m.group(1)}.tex").read_text(), t)
    for k in sorted(values, key=len, reverse=True):
        t = re.sub(r"\\" + k + r"(?![A-Za-z])(\{\})?", lambda m, k=k: values[k], t)
    for k, n in external.items():
        t = t.replace(r"\ref{" + k + "}", n)
    for f in FIGS:
        t = t.replace(f"../methodsx_figures/out/{f}", f"figures/{f}")
    t = re.sub(r"^%.*generated by make_validation_tables\.py; do not edit\n", "", t, flags=re.M)
    left = sorted(set(re.findall(r"\\(v[A-Z]\w*)", t)))
    if left:
        raise SystemExit(f"undefined number macros: {left}")
    return t


def main():
    values = macros()
    main_labels, supp_labels = labels(HERE / "build" / "main.aux"), labels(HERE / "build" / "supplement.aux")
    supp_only = {k: v for k, v in supp_labels.items() if k not in main_labels and not k.startswith(("table.", "section.", "subsection.", "Hfootnote", "page."))}
    main_only = {k: v for k, v in main_labels.items() if k not in supp_labels and not k.startswith(("table.", "section.", "subsection.", "Hfootnote", "page."))}
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "figures").mkdir(parents=True)
    (OUT / "main.tex").write_text(flatten((HERE / "main.tex").read_text(), values, supp_only))
    sup = flatten((HERE / "supplement.tex").read_text(), values, main_only)
    # the supplement cites through the article's bibliography
    sup = sup.replace(r"\end{document}", "\\bibliographystyle{unsrtnat}\n\\bibliography{references}\n\\end{document}")
    sup = sup.replace("Equation, table and section numbers without the prefix S, and all citations, refer to the main article.",
                      "Equation, table and section numbers without the prefix S refer to the main article.")
    (OUT / "supplement.tex").write_text(sup)
    shutil.copy2(HERE / "references.bib", OUT / "references.bib")
    for f in FIGS:
        shutil.copy2(FIG / f, OUT / "figures" / f)
    for f in ("main.pdf", "supplement.pdf"):
        if (HERE / "build" / f).exists():
            shutil.copy2(HERE / "build" / f, OUT / f)
    z = OUT.parent / "methodsx_overleaf.zip"
    with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
        for p in sorted(OUT.rglob("*")):
            if p.is_file() and p.suffix != ".pdf" or p.parent.name == "figures":
                zf.write(p, p.relative_to(OUT))
    print(f"-> {OUT} and {z}")


if __name__ == "__main__":
    main()
