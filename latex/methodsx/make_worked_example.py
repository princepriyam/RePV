"""Worked example for the MethodsX manuscript: one site through RePV and the simple rating model.

    python make_worked_example.py [--site LasVegas_34] [--year 2011] [--day 2011-06-21]

Runs the chain exactly as the bench does (same inputs, soiling, module fit) and writes
worked_example.tex: the hourly excerpt of one day (inputs, intermediate series, AC power)
and the annual energy and capacity factor of RePV and the simple rating model for the year. Reads the weather
cache; downloads what is missing. Never edit worked_example.tex by hand.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))

from solarmodel import bench                     # noqa: E402
from solarmodel.models import parse              # noqa: E402
from solarmodel.weather import inputs            # noqa: E402

REFS = [("rating", r"Simple rating model"), ("repv", r"\RePV")]


def weather_for(site: bench.Site, model) -> pd.DataFrame:
    s = site.system
    st = site.config.get("station", {})
    irr = inputs.irradiance("point", site.name, s, site.start, site.end, {}, st)
    met = inputs.met("point", site.name, s, site.start, site.end, {}, st)
    snow = inputs.snow(s, site.start, site.end, snowfall=model.options.snow == "nrel", depth=model.needs_snow_depth)
    return irr.join(met).join(snow)


def tex_num(x, nd=1):
    return "--" if pd.isna(x) else f"{x:.{nd}f}".replace("-", "$-$")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--site", default="LasVegas_34")
    ap.add_argument("--year", type=int, default=2011)
    ap.add_argument("--day", default="2011-06-21", help="local (standard-time) date of the hourly excerpt")
    a = ap.parse_args(argv)

    site = bench.load_site(a.site, f"{a.year}-01-01", f"{a.year}-12-31")
    rated = site.capacity_kw
    runs = {}
    for spec, _ in REFS:
        model = parse(spec)
        w = weather_for(site, model)
        runs[spec] = (w, bench.simulate(site, model, w))

    # hourly excerpt: reference L on one day, daylight hours only
    w, out = runs["repv"]
    local = out.index.tz_convert(site.config["measured"]["tz"])
    day = out[local.strftime("%Y-%m-%d") == a.day]
    day = day[day["poa_global"] > 0]
    wd = w.loc[day.index]
    rows = []
    for t in day.index:
        rows.append(" & ".join([
            t.strftime("%H:%M"), tex_num(wd.at[t, "ghi"], 0), tex_num(wd.at[t, "dni"], 0), tex_num(wd.at[t, "dhi"], 0),
            tex_num(wd.at[t, "temp_air"]), tex_num(day.at[t, "poa_global"], 0), tex_num(day.at[t, "poa_eff"], 0),
            tex_num(day.at[t, "t_cell"]), tex_num(day.at[t, "p_dc_kw"]), tex_num(day.at[t, "p_ac_kw"]),
        ]) + r" \\")
    excerpt = [
        r"\begin{table}[htbp]", r"\centering",
        rf"\caption{{Worked example, hourly excerpt: {site.config['location']['name'].split(' — ')[0]}, "
        rf"\RePV{{}}, local day {a.day} (labels in UTC, hour ending). Inputs from Table~\ref{{tab:weather}}, "
        rf"intermediate series and output from Table~\ref{{tab:outputs}}. Generated by \texttt{{make\_worked\_example.py}}.}}",
        r"\label{tab:worked_hours}", r"\small", r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{l rrr r rr r rr}", r"\toprule",
        r"Hour & $G_{\mathrm{GHI}}$ & $G_{\mathrm{DNI}}$ & $G_{\mathrm{DHI}}$ & $T_a$ & $G_{\mathrm{POA}}$ & "
        r"\texttt{poa\_eff} & $T_c$ & $P_{\mathrm{dc}}$ & $P_{\mathrm{ac}}$ \\",
        r"(UTC) & \multicolumn{3}{c}{[W\,m$^{-2}$]} & [$^{\circ}$C] & \multicolumn{2}{c}{[W\,m$^{-2}$]} & [$^{\circ}$C] & "
        r"\multicolumn{2}{c}{[kW]} \\", r"\midrule", *rows, r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

    # annual energy and capacity factor of the reference configurations
    hours = len(pd.date_range(f"{a.year}-01-01", f"{a.year}-12-31 23:00", freq="h"))
    arows = []
    for spec, lab in REFS:
        p = runs[spec][1]["p_ac_kw"]
        e = p.sum() / 1000.0                                   # MWh (hourly mean kW x 1 h)
        arows.append(f"{lab} & {tex_num(e)} & {tex_num(1000 * e / rated, 0)} & {tex_num(100 * p.sum() / (rated * hours))}" + r" \\")
    annual = [
        r"\begin{table}[htbp]", r"\centering",
        rf"\caption{{Worked example, year {a.year}: simulated AC energy, specific yield and capacity factor "
        rf"(on {rated:g}~kWp DC) of \RePV{{}} and the simple rating model, ERA5 input.}}",
        r"\label{tab:worked_year}", r"\small", r"\begin{tabular}{l rrr}", r"\toprule",
        r"Model & Energy [MWh] & Specific yield [kWh\,kWp$^{-1}$] & Capacity factor [\%] \\", r"\midrule",
        *arows, r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    (HERE / "worked_example.tex").write_text("\n".join(excerpt + annual))
    print(f"-> {HERE / 'worked_example.tex'}")


if __name__ == "__main__":
    main()
