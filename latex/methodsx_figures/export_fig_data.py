"""Export the figure data of the MethodsX paper as CSV, for the R figure scripts.

    python export_fig_data.py

Run after make_validation_tables.py (needs outputs/pvdaq_validation/bootstrap.parquet).
Site metadata, evidence classes, refinement-path steps and ablation pairs are taken from
make_validation_tables.py itself, so the figures and the tables cannot disagree.

Writes  data/sites.csv      one row per assessment site (coordinates, class, station, ...)
        data/stations.csv   MIDC stations used as station irradiance
        data/scores.csv     bootstrap point scores and intervals, every scored series
        data/path.csv       refinement-path steps (RAT, P0..P10, SDM) and their model names
        data/ablation.csv   one-at-a-time ablation pairs (feature, direction, with, without)
        fig_numbers.tex     counts used by the TikZ site-selection panel (\\f... macros)
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "methodsx"))
import make_validation_tables as mvt  # noqa: E402

DATA = HERE / "data"


def main():
    DATA.mkdir(exist_ok=True)
    st, models, steps = mvt.study()
    excluded = dict(st.get("excluded_sites", {}))
    meta = mvt.sites_meta(excluded)

    # sites: class C = calibrated (snow removal selected on the scored year)
    sites = meta.reset_index()[["site", "sid", "place", "lat", "lon", "alt", "dc_kw", "year", "station", "cls", "group"]]
    sites["evidence"] = sites["cls"].where(sites["group"] == "ind", "C")
    sites["label"] = sites["site"].map(mvt.site_label)
    sites.to_csv(DATA / "sites.csv", index=False)

    pd.DataFrame([dict(station=k, lat=v[0], lon=v[1]) for k, v in mvt.STATIONS.items()]) \
        .to_csv(DATA / "stations.csv", index=False)

    boot = pd.read_parquet(mvt.OUT / "bootstrap.parquet")
    boot = boot[boot.site.isin(meta.index)]
    boot.to_csv(DATA / "scores.csv", index=False)

    pd.DataFrame([dict(step=v, model=k) for k, v in steps.items()]).to_csv(DATA / "path.csv", index=False)

    rows = []
    for label, key, mw, mo, sw, so in mvt.FEATURES:
        rows.append(dict(feature=label.replace("~", " "), key=key, direction="Added to MOD", with_model=mw, without_model=mo))
        rows.append(dict(feature=label.replace("~", " "), key=key, direction="Removed from SYS", with_model=sw, without_model=so))
    pd.DataFrame(rows).to_csv(DATA / "ablation.csv", index=False)

    # counts of the selection panel that val_numbers.tex does not carry
    basis = pd.Series({k: v for k, v in mvt.EXCLUDED_BASIS.items() if k in excluded})
    n_nc = len(mvt.NOT_CONFIGURED)
    n_outcome = int(basis.str.contains("model output").sum())
    scr = pd.read_csv(mvt.INV / "screen.csv")
    # candidates = systems screened minus metadata exclusions, as in mvt.selection()
    st_ = scr["status"].fillna("")
    taken = sum(int(m.sum()) for m in (
        st_.str.startswith("excluded: no AC power column"), st_.str.startswith("excluded: net meter"),
        st_.str.contains("tracker"), st_.str.startswith("tier G"), st_.str.startswith("tier M"),
        st_.str.contains("lag at search bound")))
    n_cand = len(scr) + len(mvt.PRIZE) - taken
    lines = [
        "% generated by export_fig_data.py; do not edit",
        f"\\newcommand{{\\fNNotConfigured}}{{{n_nc}}}   % candidates not configured (built-in reflectors)",
        f"\\newcommand{{\\fNConfiguredSys}}{{{n_cand - n_nc}}}   % configured systems",
        f"\\newcommand{{\\fNExcluded}}{{{len(basis)}}}   % configured systems excluded after extraction",
        f"\\newcommand{{\\fNExclOutcome}}{{{n_outcome}}}   % of which the decision used model output",
        f"\\newcommand{{\\fNExclOther}}{{{len(basis) - n_outcome}}}   % of which metadata or measured series only",
    ]
    (HERE / "fig_numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"wrote {len(sites)} sites, {len(boot)} scores to {DATA}")


if __name__ == "__main__":
    main()
